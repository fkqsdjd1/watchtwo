function applyLanguage(lang) {
    function processNode(node) {
        if (node.nodeType === 3) {
            let text = node.originalText || node.textContent.trim();
            if (text.length > 0) {
                for (let key in dictionary) {
                    if (dictionary[key].tr === text || dictionary[key].en === text || key === text) {
                        if (!node.originalText) {
                            node.originalText = key;
                        }
                        break;
                    }
                }

                if (node.originalText && dictionary[node.originalText]) {
                    const langVal = dictionary[node.originalText][lang] || dictionary[node.originalText]['en'];
                    node.textContent = node.textContent.replace(node.textContent.trim(), langVal);
                }
            }
        } else if (node.nodeType === 1 && node.nodeName !== "SCRIPT" && node.nodeName !== "STYLE") {
            node.childNodes.forEach(processNode);
        }
    }

    processNode(document.body);

    const i18nElems = document.querySelectorAll("[data-i18n]");
    i18nElems.forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (dataI18n[key]) {
            const langVal = dataI18n[key][lang] || dataI18n[key].en;
            if (el.innerHTML.includes("<i ")) {
                const iconHTML = el.innerHTML.substring(0, el.innerHTML.indexOf("</i>") + 4);
                el.innerHTML = iconHTML + langVal;
            } else {
                el.textContent = langVal;
            }
        }
    }
    );

    const nameInput = document.getElementById("fullname");
    if (nameInput) {
        if (lang === 'tr')
            nameInput.placeholder = "Örn. Ahmet Yılmaz";
        else
            nameInput.placeholder = "e.g. John Doe";
    }
}
